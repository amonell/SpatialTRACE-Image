#!/usr/bin/env python3
from __future__ import annotations

import argparse
import json
import sys
from paper_paths import Path, lock_record, rendering_script

import matplotlib.pyplot as plt
from matplotlib.colors import Normalize
import numpy as np
import pandas as pd

HERE=Path(__file__).resolve();sys.path.insert(0,str(HERE.parents[2]));sys.path.insert(0,str(HERE.parents[3]))
from common import file_record,protect_outputs,write_provenance  # noqa: E402
from Figure_4.release import load_release,release_file
from Figure_4.common import require_file


def save(fig:plt.Figure,stem:Path,dpi:int,pad:float=.02)->list[Path]:
    pdf,png=stem.with_suffix('.pdf'),stem.with_suffix('.png');fig.savefig(png,dpi=dpi,bbox_inches='tight',pad_inches=pad);fig.savefig(pdf,dpi=dpi,bbox_inches='tight',pad_inches=pad);plt.close(fig);return [pdf,png]


def main()->None:
    parser=argparse.ArgumentParser(description="Render the production-v2 IF image and coordinate-prediction components used by Figure 1e.")
    parser.add_argument('--if-rgb-crop',type=Path,required=True);parser.add_argument('--if-crop-metadata',type=Path,required=True);parser.add_argument('--rari-zoom-predictions',type=Path,required=True);parser.add_argument('--frozen-registry',type=Path,required=True);parser.add_argument('--output-dir',type=Path,required=True);parser.add_argument('--dpi',type=int,default=300);parser.add_argument('--overwrite',action='store_true')
    parser.add_argument('--release-manifest',type=Path,required=True)
    args=parser.parse_args();out=args.output_dir.expanduser().resolve();names=('panel_E_if_image','panel_E_production_v2_if_crypt_villus_prediction')
    outputs=[out/f'{n}{s}' for n in names for s in ('.pdf','.png')];provenance=out/'panel_E_provenance.json';overwritten=protect_outputs(outputs+[provenance],args.overwrite)
    release=load_release(args.release_manifest);prediction_path=release_file(args.rari_zoom_predictions,release)
    registry=json.loads(require_file(args.frozen_registry).read_text());checkpoint=registry['models']['if_image_coordinate_model']['checkpoint']
    if checkpoint['sha256']!=release['checkpoint']['sha256']:raise RuntimeError('Registry does not resolve the repaired IF model')
    metadata=json.loads(require_file(args.if_crop_metadata).read_text())
    image_path=require_file(args.if_rgb_crop,metadata['output']['sha256'])
    image=np.load(image_path);cells=pd.read_parquet(prediction_path)
    bounds=metadata['bounds_fullres_px'];x0,x1,y0,y1=[bounds[k] for k in ['x_min','x_max','y_min','y_max']]
    if (x0,x1,y0,y1)!=(17000,23000,48000,52500) or image.shape[:2]!=(y1-y0,x1-x0):raise RuntimeError('Figure1e registered region changed')
    fig,ax=plt.subplots(figsize=(6,4.5));ax.imshow(image);ax.axis('off');rendered=save(fig,out/names[0],args.dpi,0)
    fig,ax=plt.subplots(figsize=(6,4.5))
    ax.scatter(cells.centroid_x_fullres_px,cells.centroid_y_fullres_px,c=cells.predicted_axis_coordinate,cmap='viridis',norm=Normalize(0,1),s=4,linewidths=0,rasterized=True);ax.set_aspect('equal');ax.set_xlim(x0,x1);ax.set_ylim(y1,y0);ax.axis('off')
    rendered+=save(fig,out/names[1],args.dpi)
    inputs=[file_record(args.release_manifest,'repaired_IF_release'),file_record(args.if_rgb_crop,'raw_vsi_multichannel_crop'),file_record(args.if_crop_metadata,'if_crop_metadata'),file_record(args.rari_zoom_predictions,'rari_production_v2_predictions'),file_record(args.frozen_registry,'frozen_registry')]
    write_provenance(provenance,script=HERE,inputs=inputs,outputs=rendered,extra={'panel':'Figure 1e','checkpoint':checkpoint,'coordinate':'crypt_villus','component_display_order':list(names),'quantification_graphs':'manual artwork; not generated by this pipeline'},overwritten=overwritten);print(provenance)


if __name__=='__main__':main()
